// R-COMM-2 / R-DATA-1 / TODO 2.0.194: generated airport-contact coverage and name data.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import { buildComContactData, readComContactInputs, serializeComContactData } from './com-contact-data.ts';
import { parseComContactData } from './src/airport-contact-data.ts';

const root = new URL('./public/airports/', import.meta.url);
const committedText = readFileSync(new URL('com-contact.json', root), 'utf8');
const committed = JSON.parse(committedText);

test('committed com-contact.json is regenerated byte-for-byte from the hash-pinned inputs', () => {
  const inputs = readComContactInputs();
  assert.equal(serializeComContactData(buildComContactData(inputs)), committedText, 'run: node com-contact-data.ts');
  assert.equal(committed.inputs.com_sha256, JSON.parse(readFileSync(new URL('com-manifest.json', root), 'utf8')).sha256);
  assert.equal(committed.inputs.airports_sha256, JSON.parse(readFileSync(new URL('manifest.json', root), 'utf8')).sha256);
  assert.equal(committed.inputs.world_catalogue_sha256, JSON.parse(readFileSync(new URL('world/manifest.json', root), 'utf8')).sha256);
});

test('client validation accepts the committed data and its coverage marks interior complete, borders incomplete', () => {
  const data = parseComContactData(committed);
  const at = (lat: number, lon: number) => data.coverage.rows[Math.floor((lat - 47) / 0.25)][Math.floor((lon - 6) / 0.25)];
  assert.equal(at(49.96, 8.643), '1', 'EDFE'); assert.equal(at(48.78, 9.2), '1', 'Stuttgart');
  assert.equal(at(50.4, 6.8), '0', 'Büchel/NRW border'); assert.equal(at(47.67, 9.51), '0', 'Friedrichshafen/Swiss-Austrian border');
  assert.equal(data.regionalNames.get('langen information')! >= 189, true);
});

test('client validation rejects malformed coverage and name tables', () => {
  const clone = () => JSON.parse(committedText);
  const cases: [string, (v: any) => void][] = [
    ['identity', v => { v.id = 'other'; }],
    ['bounds', v => { v.coverage.bounds = [5, 47, 14, 51.75]; }],
    ['radius below release range', v => { v.coverage.radius_nm = 20; }],
    ['row length', v => { v.coverage.rows[0] += '1'; }],
    ['row characters', v => { v.coverage.rows[0] = v.coverage.rows[0].replace(/^./, '2'); }],
    ['complete count', v => { v.coverage.complete_cells += 1; }],
    ['input hash', v => { v.inputs.com_sha256 = 'x'; }],
    ['small regional count', v => { v.regional_names[0][1] = 2; }],
    ['duplicate name', v => { v.regional_names.push(v.regional_names[0]); }],
  ];
  for (const [name, mutate] of cases) { const v = clone(); mutate(v); assert.throws(() => parseComContactData(v), /Invalid airport contact data/, name); }
});
