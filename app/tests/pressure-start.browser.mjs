// R-AIR-3 / TODO2.0.159: real worker/WASM and the actual pressure UI component.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const app = fileURLToPath(new URL('..', import.meta.url));
const output = fileURLToPath(new URL('../../output/flight/', import.meta.url));
const origin = 'http://127.0.0.1:5361';
const server = spawn(process.execPath, ['--input-type=module', '-e', `import{createServer}from'vite';const s=await createServer({cacheDir:'../output/flight/pressure-start-vite',server:{host:'127.0.0.1',port:5361,strictPort:true,hmr:false,watch:{ignored:['**/*']}}});await s.listen();s.printUrls();`], { cwd: app, stdio: 'pipe' });
let log = '', browser;
server.stdout.on('data', data => { log += data; });
server.stderr.on('data', data => { log += data; });
const result = { checks: [], errors: [] };
try {
  await mkdir(output, { recursive: true });
  for (let i = 0; i < 100 && !log.includes('Local:'); i++) await new Promise(resolve => setTimeout(resolve, 100));
  assert(log.includes('Local:'), log);
  browser = await chromium.launch({ headless: true, ...(process.env.CHROME ? { executablePath: process.env.CHROME } : { channel: 'chrome' }) });
  result.browser = browser.version();
  const page = await browser.newPage({ viewport: { width: 1000, height: 850 }, serviceWorkers: 'block' });
  page.on('pageerror', error => result.errors.push(String(error)));
  await page.route(`${origin}/pressure-fixture.html`, route => route.fulfill({ contentType: 'text/html', body: `<!doctype html><title>Pressure startup</title><main id="panel" style="width:300px"></main><script type="module">
import '/src/style.css';
import{createPressureAltimeterPanel}from'/src/pressure-altimeter-panel.ts';
window.messages=[];window.commands=[];window.review=false;window.locked=false;
window.worker=new Worker('/studies/e1-browser/sim/worker.js',{type:'module'});
window.panel=createPressureAltimeterPanel({container:document.querySelector('#panel'),onSetting(setting_pa){commands.push(setting_pa);worker.postMessage({type:'altimeter',setting_pa});},onOpen(){},onClose(){}});
worker.onmessage=({data})=>{messages.push(data);if(data.type==='state'){window.state=data;panel.update(data,review,locked);}};
window.init=(altitude)=>{messages.length=0;worker.postMessage({type:'init',aircraft:'c172x',kap140:true,terrain:false,dt_s:1/120,state_hz:60,ic:{lat_rad:47.15*Math.PI/180,lon_rad:8.45*Math.PI/180,alt_msl_m:altitude,heading_rad:1,tas_mps:45}});};
window.ready=true;
</script>` }));
  await page.goto(`${origin}/pressure-fixture.html`);
  await page.waitForFunction(() => window.ready);
  const send = async (message, type) => {
    const index = await page.evaluate(message => { const i=messages.length; worker.postMessage(message); return i; }, message);
    await page.waitForFunction(({index,type}) => messages.slice(index).some(m=>m.type===type||m.type==='error'), {index,type});
    const reply = await page.evaluate(({index,type}) => messages.slice(index).find(m=>m.type===type||m.type==='error'), {index,type});
    assert.notEqual(reply.type, 'error', reply.message); return reply;
  };
  const init = async altitude => {
    await page.evaluate(altitude => init(altitude), altitude);
    await page.waitForFunction(() => messages.some(m=>m.type==='state'||m.type==='error'));
    const failure = await page.evaluate(() => messages.find(m=>m.type==='error'));
    assert(!failure, failure?.message);
  };
  await init(3000);
  const initial = await page.evaluate(() => state);
  assert(initial.altimeter_qfe_pa < 80000);
  assert.equal(await page.locator('#altimeter-availability').isHidden(), true);
  await page.locator('#altimeter-open').click();
  assert.equal(await page.locator('#altimeter-qfe').isDisabled(), true);
  assert.equal(await page.locator('#altimeter-qnh').isEnabled(), true);
  assert.equal(await page.locator('#altimeter-std').isEnabled(), true);
  assert.match(await page.locator('#altimeter-datum').textContent(), /outside.*800–1100 hPa.*use QNH or standard/);
  const engaged = await send({type:'autopilot-capture'}, 'state');
  assert.equal(engaged.kap_engaged, 1);
  const apFields = state => Object.fromEntries(Object.entries(state).filter(([key]) => key.startsWith('kap_') || key.startsWith('ap_')));
  const before = await send({type:'stats'}, 'stats');
  await page.locator('#altimeter-qfe').evaluate(button => button.click());
  assert.deepEqual(await page.evaluate(() => commands), []);
  await page.locator('#altimeter-setting').fill('1000');
  await page.locator('#altimeter-setting').press('Tab');
  await page.waitForFunction(() => state.altimeter_setting_pa===100000);
  await page.locator('#altimeter-std').click();
  await page.waitForFunction(() => state.altimeter_setting_pa===101325);
  await page.locator('#altimeter-qnh').click();
  await page.waitForFunction(() => state.altimeter_setting_pa===state.altimeter_qnh_pa);
  assert.deepEqual(await page.evaluate(() => Object.fromEntries(Object.entries(state).filter(([key]) => key.startsWith('kap_') || key.startsWith('ap_')))), apFields(engaged));
  const after = await send({type:'stats'}, 'stats');
  for (const key of ['step','t_s','digest','final_state']) assert.deepEqual(after[key], before[key]);
  result.checks.push('3000m real worker pressure remains visible; unsupported QFE disabled/explained; manual/QNH/STD work without paused native or engaged-AP changes');
  await page.screenshot({path:`${output}/pressure-start-high.png`});
  await page.locator('#altimeter-close').click();
  await init(500);
  await page.locator('#altimeter-open').click();
  assert.equal(await page.locator('#altimeter-qfe').isEnabled(), true);
  await page.locator('#altimeter-qfe').click();
  await page.waitForFunction(() => state.altimeter_indicated_m===0);
  result.checks.push('500m launch QFE remains selectable and reads zero');
  await page.evaluate(() => { review=true;panel.update(state,true); });
  assert.equal(await page.locator('#altimeter-dialog').evaluate(dialog=>dialog.open), false);
  assert.equal(await page.locator('#altimeter-open').isDisabled(), true);
  await page.evaluate(() => { review=false;locked=true;panel.update(state,false,true); });
  assert.equal(await page.locator('#altimeter-open').isDisabled(), true);
  await page.evaluate(() => { locked=false;panel.update(null,false); });
  assert.equal(await page.locator('#altimeter-availability').isVisible(), true);
  assert.equal(await page.locator('#altimeter-open').isDisabled(), true);
  result.checks.push('Review/read-only/unavailable states keep existing modal and setting guards');
  assert.deepEqual(result.errors, []);
  result.scope='Actual pressure component wired to unchanged WASM production worker; terrain off. Full simulator layout and aircraft fidelity not evaluated.';
  result.initial=initial;
  await writeFile(`${output}/pressure-start-browser.json`, JSON.stringify(result,null,2)+'\n');
  console.log(`Pressure startup browser: ${result.checks.length} groups passed`);
} finally { await browser?.close(); server.kill(); }
