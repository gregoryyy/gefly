#!/usr/bin/env python3
"""Generate coarse country/state photo-source outlines from pinned Natural Earth files.

Usage: extract-photo-outlines.py ADMIN0.geojson ADMIN1.geojson > app/src/country-imagery-outlines.ts

The outlines decide which photo sources are named in status text and credits.
They are generalized public-domain cartography, not imagery footprints.
Standard library only; deterministic output.
"""
import hashlib
import json
import math
import sys
from pathlib import Path

ADMIN0_SHA256 = '239eec57ac17f100a11e2536cffc56752c318b50ae765b0918ff7aab4ce8f255'
ADMIN1_SHA256 = '22d0e3ad85eb3e27f17cabf8ba2d50e554fbc27a87796ff891d958185da62fb5'
OUTPUT_SHA256 = 'e6fdb5f33672a7a1ac60873f9a8e02e4053bac80a270c10bb0dc97d3d6fe8ce7'
TOLERANCE_DEG = 0.01
# Source id -> (file, property, values). Holes are dropped: outlines are unions of outer rings.
SELECTION = {
    'ch': ('admin0', 'ADM0_A3', ('CHE', 'LIE')),
    'at': ('admin0', 'ADM0_A3', ('AUT',)),
    'nrw': ('admin1', 'iso_3166_2', ('DE-NW',)),
    'bb': ('admin1', 'iso_3166_2', ('DE-BB', 'DE-BE')),
    'es': ('admin0', 'ADM0_A3', ('ESP',)),
}


def load(path, expected):
    raw = Path(path).read_bytes()
    if hashlib.sha256(raw).hexdigest() != expected:
        raise ValueError(f'Natural Earth input hash mismatch: {path}')
    return json.loads(raw)


def simplify(points, tolerance, scale):
    """Iterative Douglas-Peucker in locally scaled degrees; keeps both ends."""
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        first, last = stack.pop()
        ax, ay = points[first][0] * scale, points[first][1]
        bx, by = points[last][0] * scale, points[last][1]
        dx, dy = bx - ax, by - ay
        length = math.hypot(dx, dy)
        best, index = -1.0, -1
        for i in range(first + 1, last):
            px, py = points[i][0] * scale, points[i][1]
            if length == 0:
                distance = math.hypot(px - ax, py - ay)
            else:
                distance = abs(dx * (ay - py) - (ax - px) * dy) / length
            if distance > best:
                best, index = distance, i
        if index >= 0 and best > tolerance:
            keep[index] = True
            stack.append((first, index))
            stack.append((index, last))
    return [p for p, k in zip(points, keep) if k]


def outline(features):
    rings = []
    for feature in features:
        geometry = feature['geometry']
        polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        if geometry['type'] not in ('Polygon', 'MultiPolygon'):
            raise ValueError('unexpected geometry')
        for polygon in polygons:
            ring = polygon[0]
            scale = math.cos(math.radians(sum(p[1] for p in ring) / len(ring)))
            # Split the closed ring in two so both halves keep their far vertex.
            middle = len(ring) // 2
            simple = simplify(ring[:middle + 1], TOLERANCE_DEG, scale)[:-1] + simplify(ring[middle:], TOLERANCE_DEG, scale)
            rounded = []
            for lon, lat in simple:
                point = (round(lon, 3), round(lat, 3))
                if not rounded or rounded[-1] != point:
                    rounded.append(point)
            if rounded[0] == rounded[-1]:
                rounded.pop()
            if len(set(rounded)) >= 3:
                rings.append([value for point in rounded for value in point])
    return rings


def main():
    sources = {'admin0': load(sys.argv[1], ADMIN0_SHA256), 'admin1': load(sys.argv[2], ADMIN1_SHA256)}
    lines = [
        '// Generated by utils/scenery/extract-photo-outlines.py from pinned Natural Earth v5.1.1',
        '// (public domain); see utils/scenery/photo-outlines-source.md. Do not edit by hand.',
        '// Coarse outer rings ([lon, lat, ...] degrees) for naming plausible sources only.',
        "import type { PhotoCountry } from './country-imagery.ts';",
        '',
        'export const COUNTRY_PHOTO_OUTLINES: Readonly<Record<PhotoCountry, readonly (readonly number[])[]>> = {',
    ]
    for source, (kind, key, values) in SELECTION.items():
        features = [f for f in sources[kind]['features'] if f['properties'].get(key) in values]
        if len(features) != len(values):
            raise ValueError(f'unexpected feature count for {source}')
        rings = outline(features)
        lines.append(f'  {source}: [')
        for ring in rings:
            lines.append('    [' + ','.join(format(v, 'g') for v in ring) + '],')
        lines.append('  ],')
    lines.append('};')
    output = '\n'.join(lines) + '\n'
    digest = hashlib.sha256(output.encode()).hexdigest()
    if OUTPUT_SHA256 and digest != OUTPUT_SHA256:
        raise ValueError(f'generated outline hash mismatch: {digest}')
    sys.stdout.write(output)


if __name__ == '__main__':
    main()
